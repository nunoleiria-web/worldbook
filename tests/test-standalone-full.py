from playwright.sync_api import sync_playwright
S='/tmp/claude-0/-home-claude/b39ebeaf-d692-5171-bcf0-8dcd27999322/scratchpad/'
errs=[]
with sync_playwright() as p:
    b=p.chromium.launch()
    ctx=b.new_context(viewport={'width':1100,'height':800}, accept_downloads=True); pg=ctx.new_page()
    pg.on('pageerror',lambda e:errs.append(str(e)))
    pg.on('console',lambda m:errs.append(m.text) if m.type=='error' and 'TUNNEL' not in m.text else None)
    pg.route('**/*fonts.g*', lambda r: r.abort())
    pg.goto('http://localhost:8123/'); pg.wait_for_timeout(500)
    pg.click('text=Nova viagem'); pg.fill('#f-title','Algarve'); pg.fill('#f-country','Portugal'); pg.fill('#f-start','2026-08-01'); pg.fill('#f-end','2026-08-02')
    pg.click('button[type=submit]'); pg.wait_for_timeout(400)
    pg.fill('#day-2026-08-01','Praia de manhã e jantar no porto.'); pg.dispatch_event('#day-2026-08-01','change')
    with pg.expect_file_chooser() as fc: pg.click('text=Adicionar fotos')
    fc.value.set_files([S+'f1.jpg',S+'f2.jpg']); pg.wait_for_timeout(1500)
    print('th', pg.evaluate("[...document.querySelectorAll('.wall img')].map(i=>i.naturalWidth)"))
    with pg.expect_download() as d: pg.click('text=Exportar PDF')
    pg.wait_for_timeout(500)
    d.value.save_as(S+'out.pdf'); print('pdf', d.value.suggested_filename)
    pg.click('text=Todas as viagens')
    with pg.expect_download() as d2: pg.click('text=Guardar cópia')
    d2.value.save_as(S+'backup.json'); print('backup', d2.value.suggested_filename)
    pg.click('text=Modo discreto'); pg.screenshot(path=S+'shot-disc.png')
    ctx.close()
    ctx2=b.new_context(viewport={'width':1100,'height':800}); pg2=ctx2.new_page()
    pg2.on('pageerror',lambda e:errs.append(str(e)))
    pg2.route('**/*fonts.g*', lambda r: r.abort())
    pg2.goto('http://localhost:8123/'); pg2.wait_for_timeout(600)
    print('fresh empty:', 'vazio' in pg2.inner_text('#app'))
    pg2.set_input_files('#restore-input', S+'backup.json'); pg2.wait_for_timeout(1500)
    pg2.click('#tab-viagens'); pg2.wait_for_timeout(300)
    print('restored cards', pg2.locator('.card').count(), pg2.evaluate("[...document.querySelectorAll('.card img')].map(i=>i.naturalWidth)"))
    b.close()
print('ERRORS',errs)
